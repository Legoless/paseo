import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(appRoot, "../..");
const entry = path.join(appRoot, "src/terminal/webview/terminal-emulator-webview-entry.ts");
const output = path.join(appRoot, "src/terminal/webview/terminal-emulator-webview-html.ts");
const guestOutput = path.join(appRoot, "public/terminal-guest.html");

async function resolveTsPath(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    `${basePath}.js`,
    `${basePath}.jsx`,
    path.join(basePath, "index.ts"),
    path.join(basePath, "index.tsx"),
    path.join(basePath, "index.js"),
    path.join(basePath, "index.jsx"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isFile()) return candidate;
    } catch {
      // try next candidate
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "paseo-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTsPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
    build.onResolve({ filter: /^@server\// }, async (args) => ({
      path: await resolveTsPath(
        path.join(repoRoot, "packages/server/src", args.path.slice("@server/".length)),
      ),
    }));
  },
};

async function buildBundle(target) {
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target,
    loader: {
      ".css": "text",
    },
    plugins: [aliasPlugin],
    logLevel: "info",
  });

  const js = result.outputFiles[0]?.text;
  if (!js) {
    throw new Error("terminal webview bundle produced no JavaScript");
  }
  return js;
}

function buildHtml(js) {
  return `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"
    />
  </head>
  <body>
    <script>${js}</script>
  </body>
</html>`;
}

// Native RN-WebView host: the bundle is embedded as a string module.
const nativeHtml = buildHtml(await buildBundle(["ios15", "chrome100"]));
const contents = `// Generated by packages/app/scripts/build-terminal-webview-html.mjs.
// Do not edit by hand.

export const terminalEmulatorWebViewHtml = ${JSON.stringify(nativeHtml)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repoRoot, output)} (${nativeHtml.length} bytes)`);

// Electron `<webview>` host: a same-origin static page served from public/ (dev) and copied into
// dist/ on export. Same entry, newer target.
const guestHtml = buildHtml(await buildBundle(["chrome120"]));
await fs.writeFile(guestOutput, guestHtml);
console.log(`Wrote ${path.relative(repoRoot, guestOutput)} (${guestHtml.length} bytes)`);
