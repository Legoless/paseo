import type { AgentHookPluginFileInstallStrategy } from "../agent-hook-installer.js";

// Both generations discover the same file. Their loaders select the entrypoint:
// OpenCode 1 calls server(); OpenCode 2 calls setup(). Keep their event contracts
// separate: V1 publishes status snapshots, V2 publishes execution transitions.
export const OPENCODE_PLUGIN_SOURCE = [
  "const V2_ACTIONS = {",
  '  "session.execution.started": "busy",',
  '  "session.retry.scheduled": "retry",',
  '  "session.execution.succeeded": "idle",',
  '  "session.execution.failed": "idle",',
  '  "session.execution.interrupted": "idle",',
  "};",
  "",
  // OpenCode publishes child sessions on the same bus as the visible session.
  // Resolve their ancestry even after resume, when session.created was missed.
  "function createReporter(getSession, directory) {",
  "  const sessions = new Map();",
  "  const activity = new Map();",
  "  let activeRoot = null;",
  "  let lastReport = null;",
  "  let pending = Promise.resolve();",
  "  async function rootOf(sessionID) {",
  "    const visited = new Set();",
  "    while (sessionID && !visited.has(sessionID)) {",
  "      visited.add(sessionID);",
  "      if (!sessions.has(sessionID)) sessions.set(sessionID, await getSession(sessionID));",
  "      const info = sessions.get(sessionID);",
  "      if (!info.parentID) return info;",
  "      sessionID = info.parentID;",
  "    }",
  "    return null;",
  "  }",
  "  return (action, data) => {",
  "    if (!process.env.PASEO_TERMINAL_ID || !action || !data) return Promise.resolve();",
  "    pending = pending.then(async () => {",
  '      if (action === "session") {',
  "        sessions.set(data.id, data);",
  "        return;",
  "      }",
  "      const sessionID = data.sessionID;",
  '      if (typeof sessionID !== "string" || !sessionID) return;',
  "      const root = await rootOf(sessionID);",
  // V2 subscriptions span locations; a child may itself use a different cwd.
  "      if (!root || root.directory !== directory || (activeRoot && root.id !== activeRoot)) return;",
  "      let state = activity.get(sessionID);",
  "      if (!state) {",
  "        state = { running: false, permissions: new Set() };",
  "        activity.set(sessionID, state);",
  "      }",
  '      if (action === "busy" || action === "retry") state.running = true;',
  '      else if (action === "idle" || action === "deleted") {',
  "        state.running = false;",
  "        state.permissions.clear();",
  '      } else if (action === "permission.asked") {',
  '        if (typeof data.id !== "string") return;',
  "        state.permissions.add(data.id);",
  '      } else if (action === "permission.replied") {',
  '        if (typeof data.requestID !== "string") return;',
  "        state.permissions.delete(data.requestID);",
  "        state.running = true;",
  "      } else return;",
  "      if (!activeRoot) {",
  "        if (!state.running && state.permissions.size === 0) return;",
  "        activeRoot = root.id;",
  "      }",
  "      let running = false;",
  "      let waiting = false;",
  "      for (const [id, current] of activity) {",
  "        if ((await rootOf(id))?.id !== activeRoot) continue;",
  "        running ||= current.running;",
  "        waiting ||= current.permissions.size > 0;",
  "      }",
  '      let event = "session.status.idle";',
  '      if (waiting) event = "permission.asked";',
  '      else if (running) event = "session.status.busy";',
  "      const session_id = activeRoot;",
  "      if (!running && !waiting) activeRoot = null;",
  "      const signature = JSON.stringify([session_id, event]);",
  "      if (signature === lastReport) return;",
  "      lastReport = signature;",
  // Queue both event processing and CLI completion: busy and idle must not race.
  '      const child = Bun.spawn([process.env.PASEO_HOOK_CLI || "paseo", "hooks", "opencode", event], {',
  "        stdin: new Blob([JSON.stringify({ session_id })]),",
  '        stdout: "ignore",',
  '        stderr: "ignore",',
  "      });",
  "      await child.exited;",
  "    }).catch(() => {});",
  "    return pending;",
  "  };",
  "}",
  "",
  "export default {",
  '  id: "paseo-terminal-activity",',
  "  server(input) {",
  "    const report = createReporter(async (sessionID) => {",
  "      const response = await input.client.session.get({",
  "        path: { id: sessionID }, query: { directory: input.directory },",
  "      });",
  "      return response.data;",
  "    }, input.directory);",
  "    return {",
  "      event: async ({ event }) => {",
  "        const data = event.properties;",
  '        if (event.type === "session.created" || event.type === "session.updated") return report("session", data?.info);',
  '        if (event.type === "session.deleted") return report("deleted", { sessionID: data?.info?.id });',
  "        let action = null;",
  '        if (event.type === "session.status") action = data?.status?.type;',
  '        else if (event.type.startsWith("permission.")) action = event.type;',
  "        await report(action, data);",
  "      },",
  "    };",
  "  },",
  "  setup(ctx) {",
  "    const report = createReporter(async (sessionID) => {",
  "      const info = await ctx.session.get({ sessionID });",
  "      return { ...info, directory: info.location.directory };",
  "    }, ctx.location.directory);",
  "    const controller = new AbortController();",
  "    void (async () => {",
  "      for await (const event of ctx.event.subscribe({ signal: controller.signal })) {",
  "        const data = event.data;",
  '        if (event.type === "session.created") {',
  '          await report("session", { ...data, id: data.sessionID, directory: data.location.directory });',
  "          continue;",
  "        }",
  "        let action = V2_ACTIONS[event.type] ?? null;",
  '        if (event.type === "session.deleted") action = "deleted";',
  '        else if (event.type.startsWith("permission.")) action = event.type;',
  "        await report(action, data);",
  "      }",
  "    })().catch(() => {});",
  "    return () => controller.abort();",
  "  },",
  "};",
  "",
].join("\n");

export function createOpenCodePluginInstallStrategy(): AgentHookPluginFileInstallStrategy {
  return {
    kind: "plugin-file",
    configDir: "opencode",
    configDirBase: "xdg-config",
    configFile: "plugins/paseo-terminal-activity.js",
    configDirEnvOverride: "OPENCODE_CONFIG_DIR",
    hookMarker: "paseo hooks opencode",
    source: OPENCODE_PLUGIN_SOURCE,
  };
}
